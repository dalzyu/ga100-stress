"""NVDEC verification: N concurrent decode sessions over a committed synthetic clip.

The clip (smooth sine gradients, H.264 1280x720, no B-frames) is generated by
tools/gen_nvdec_vector.py. Pass rules: every session decodes all frames,
per-frame hashes are identical across sessions (decoder determinism), and the
decoded content matches the known synthetic source (correlation and PSNR).
NVDEC output is not assumed bit-exact against other decoders.
"""

from __future__ import annotations

import ctypes
import hashlib
import threading
import time
from pathlib import Path

import numpy as np
import torch

import PyNvVideoCodec as nvc

from .guard import require_bare_gpu
from .report import Result

WIDTH, HEIGHT, FRAMES = 1280, 720, 24
CORR_MIN = 0.95
PSNR_MIN_DB = 30.0

_DATA = Path(__file__).resolve().parent / "data"


def _source_frames(n: int) -> np.ndarray:
    ys, xs = np.meshgrid(
        np.arange(HEIGHT, dtype=np.float32),
        np.arange(WIDTH, dtype=np.float32),
        indexing="ij",
    )
    return np.stack(
        [
            np.clip(128 + 60 * np.sin(xs / 24 + i * 0.35) * np.cos(ys / 24), 0, 255).astype(
                np.uint8
            )
            for i in range(n)
        ]
    )


def _packets() -> list[bytes]:
    """Demux the clip into materialized packets (the demuxer reuses its buffer)."""
    dm = nvc.CreateDemuxer(str(_DATA / "nvdec_test_1280x720.mp4"))
    out = []
    while True:
        pkt = dm.Demux()
        if pkt is None or not pkt.bsl or not pkt.bsl_data:
            break
        out.append(ctypes.string_at(pkt.bsl_data, pkt.bsl))
        if len(out) > 1000:
            break
    return out


def _y_plane(frame) -> np.ndarray:
    planes = frame.cuda()  # list of per-plane CAIMemoryViews (host memory)
    mv = planes[0] if isinstance(planes, list) else planes
    h, w = mv.shape[0], mv.shape[1]
    buf = (ctypes.c_ubyte * (h * w)).from_address(mv.dataptr)
    return np.frombuffer(buf, dtype=np.uint8).reshape(h, w).copy()


def _decode_session(packets: list[bytes], gpuid: int, out: dict, idx: int, keep_pixels: bool) -> None:
    try:
        dec = nvc.CreateDecoder(
            gpuid=gpuid,
            codec=nvc.cudaVideoCodec.H264,
            usedevicememory=False,
            latency=nvc.DisplayDecodeLatencyType.ZERO,
        )
        hashes: list[str] = []
        pixels: list[np.ndarray] = []
        for i, data in enumerate(packets):
            buf = ctypes.create_string_buffer(data)
            pd = nvc.PacketData()
            pd.bsl_data = ctypes.addressof(buf)
            pd.bsl = len(data)
            pd.pts = i
            for frame in dec.Decode(pd):
                y = _y_plane(frame)
                hashes.append(hashlib.sha256(y.tobytes()).hexdigest())
                if keep_pixels:
                    pixels.append(y)
        pd = nvc.PacketData()  # empty packet flushes the pipeline tail
        pd.bsl_data = 0
        pd.bsl = 0
        for frame in dec.Decode(pd):
            y = _y_plane(frame)
            hashes.append(hashlib.sha256(y.tobytes()).hexdigest())
            if keep_pixels:
                pixels.append(y)
        out[idx] = (hashes, pixels)
    except Exception as e:  # noqa: BLE001 - session failure is the result
        out[idx] = e


def run(device: int = 0, sessions: int = 5) -> Result:
    require_bare_gpu(device)
    torch.cuda.set_device(device)
    metrics: dict = {}
    notes: list[str] = []

    packets = _packets()
    metrics["packets"] = len(packets)

    out: dict = {}
    threads = [
        threading.Thread(target=_decode_session, args=(packets, device, out, i, i == 0))
        for i in range(sessions)
    ]
    t0 = time.perf_counter()
    for t in threads:
        t.start()
    for t in threads:
        t.join()
    metrics["sessions"] = sessions
    metrics["decode_s"] = round(time.perf_counter() - t0, 2)

    errors = [v for v in out.values() if isinstance(v, Exception)]
    for e in errors:
        notes.append(f"session failed: {type(e).__name__}: {e}")
    hash_lists = [v[0] for v in out.values() if not isinstance(v, Exception)]

    hash_ok = not errors and len(hash_lists) == sessions
    if hash_ok:
        n_decoded = len(hash_lists[0])
        metrics["frames_decoded"] = n_decoded
        same = all(h == hash_lists[0] for h in hash_lists)
        metrics["cross_session_hashes_match"] = same
        if n_decoded != FRAMES:
            notes.append(f"decoded {n_decoded} frames, expected {FRAMES}")
            hash_ok = False
        elif not same:
            notes.append("decode sessions disagree on frame hashes")
            hash_ok = False
    else:
        metrics["frames_decoded"] = 0

    corr = psnr_min = None
    if not errors and out.get(0) is not None and len(out[0][1]) == FRAMES:
        src = _source_frames(FRAMES)
        corrs, psnrs = [], []
        for a, b in zip(src, out[0][1]):
            x = a.astype(np.float64)
            yv = b.astype(np.float64)
            corrs.append(float(np.corrcoef(x.ravel(), yv.ravel())[0, 1]))
            mse = float(np.mean((x - yv) ** 2))
            psnrs.append(99.0 if mse == 0 else float(10 * np.log10(255.0**2 / mse)))
        corr = round(min(corrs), 4)
        psnr_min = round(min(psnrs), 2)
        metrics["min_content_correlation"] = corr
        metrics["psnr_vs_source_min_db"] = psnr_min
        if corr < CORR_MIN:
            notes.append(f"content correlation {corr} below {CORR_MIN}")
        if psnr_min < PSNR_MIN_DB:
            notes.append(f"worst-frame PSNR {psnr_min} dB below {PSNR_MIN_DB} dB")

    passed = bool(
        hash_ok
        and corr is not None
        and corr >= CORR_MIN
        and psnr_min is not None
        and psnr_min >= PSNR_MIN_DB
    )
    return Result(name="nvdec", passed=passed, metrics=metrics, notes=notes)
